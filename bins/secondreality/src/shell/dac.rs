//! The DAC a VGA mode set leaves, which a run's first frames are drawn through.

use sr_engine::Palette;

/// The emulator's mode-set DAC: `INT10_SetVideoMode`'s `M_VGA` case writes `palette.vga`
/// (`ints/int10_modes.cpp:1977-1987`, `:1152-1159`), whose first sixteen entries are
/// `cga_colors_default` (`:404-412`). It writes 248 triples, so the last eight stay black.
///
/// The shell installs it once, as the original's shell sets mode 13h once per block entry
/// (`MAIN/U2.ASM:806-808`, `:906-908`), and each part inherits what the one before left:
/// BEGLOGO's 430 is index 15 over it, before the part writes the DAC (`BEG/BEG.C:20-34`).
pub(crate) fn hardware_default_palette() -> Palette {
    let mut dac = Palette::new();
    for (index, rgb) in VGA_DEFAULT_PALETTE.iter().enumerate() {
        dac.set_entry(index as u8, *rgb);
    }
    dac
}

